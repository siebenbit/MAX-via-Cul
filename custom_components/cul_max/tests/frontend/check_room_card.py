"""Browser checks with simulated HA and no RF hardware or runtime dependencies."""
from pathlib import Path
from preview_server import preview_server
from playwright.sync_api import sync_playwright, expect

fixture = Path(__file__).with_name("room-card-harness.html").resolve().as_uri()
with preview_server() as origin, sync_playwright() as p:
    browser = p.chromium.launch(headless=True, args=["--no-sandbox"])
    page = browser.new_page(viewport={"width": 1200, "height": 1300}, locale="de-DE")
    errors = []
    page.on("pageerror", lambda err: errors.append(str(err)))
    page.goto(origin + "/tests/frontend/room-card-harness.html")
    card = page.locator("cul-max-room-config-card")
    expect(card.get_by_role("heading", name="MAX! Raumkonfiguration")).to_be_visible()
    expect(card.get_by_text("Gespeicherte Konfiguration für", exact=False)).to_have_count(0)
    help_button = card.get_by_role("button", name="Hilfe zu Komforttemperatur", exact=True)
    tooltip = card.locator("#help-comfort_temperature")
    expect(tooltip).to_be_hidden()
    help_button.hover()
    expect(tooltip).to_be_visible()
    expect(tooltip).to_contain_text("Die Temperaturen im Wochenplan bleiben unverändert.")
    card.get_by_role("heading", name="MAX! Raumkonfiguration").hover()
    expect(tooltip).to_be_hidden()
    help_button.focus()
    expect(tooltip).to_be_visible()
    help_button.press("Escape")
    expect(tooltip).to_be_hidden()
    help_button.click()
    expect(tooltip).to_be_visible()
    help_button.click()
    expect(tooltip).to_be_hidden()
    help_button.click()
    card.get_by_role("button", name="Hilfe zu Ecotemperatur", exact=True).click()
    expect(tooltip).to_be_hidden()
    expect(card.locator("#help-eco_temperature")).to_be_visible()
    page.screenshot(path="/tmp/cul-max-room-tooltip-desktop.png", full_page=True)
    card.get_by_role("heading", name="MAX! Raumkonfiguration").click()
    expect(card.locator("#help-eco_temperature")).to_be_hidden()
    comfort = card.get_by_role("spinbutton", name="Komforttemperatur", exact=True)
    comfort.fill("22")
    expect(card.get_by_role("button", name="Speichern", exact=True)).to_be_enabled()
    expect(card.get_by_role("spinbutton", name="Komforttemperatur", exact=True)).to_have_value("22")
    assert page.evaluate("calls.length") == 0
    time_input = card.get_by_label("Schaltzeit 2", exact=True)
    time_input.fill("06:30")
    time_input.blur()
    expect(time_input).to_have_value("06:30")
    expect(card.get_by_role("button", name="Schaltzeit 1 löschen", exact=True)).to_be_disabled()
    first = card.get_by_role("spinbutton", name="Temperatur Abschnitt 1", exact=True)
    first.fill("17.5")
    assert page.evaluate("card._changes.week_profile.monday[0].temperature") == "17.5"
    monday = card.get_by_role("tab", name="Montag, ungespeicherte Änderungen", exact=True)
    expect(monday.locator(".dirty-dot")).to_be_visible()
    expect(card.locator("[data-template]")).to_have_count(0)
    # Restoring the original rows removes the marker immediately.
    first.fill("17")
    time_input.fill("06:00")
    expect(card.get_by_role("tab", name="Montag", exact=True).locator(".dirty-dot")).to_have_count(0)
    first.fill("17.5")
    time_input.fill("06:30")
    card.get_by_role("button", name="Tag auf andere Tage kopieren …").click()
    expect(card.get_by_role("checkbox", name="Montag", exact=True)).to_have_count(0)
    expect(card.get_by_role("button", name="Auf 0 Tage übernehmen")).to_be_disabled()
    card.get_by_role("button", name="Alle auswählen", exact=True).click()
    expect(card.get_by_role("button", name="Auf 6 Tage übernehmen")).to_be_enabled()
    card.get_by_role("button", name="Auswahl aufheben", exact=True).click()
    expect(card.get_by_role("button", name="Auf 0 Tage übernehmen")).to_be_disabled()
    card.get_by_role("checkbox", name="Dienstag", exact=True).check()
    card.get_by_role("checkbox", name="Mittwoch", exact=True).check()
    page.screenshot(path="/tmp/cul-max-room-copy-desktop.png", full_page=True)
    card.get_by_role("button", name="Auf 2 Tage übernehmen", exact=True).click()
    assert page.evaluate("Object.keys(card._changes.week_profile).sort()") == ["monday", "tuesday", "wednesday"]
    assert page.evaluate("calls.length") == 0
    card.get_by_role("tab", name="Dienstag, ungespeicherte Änderungen", exact=True).click()
    expect(card.get_by_role("spinbutton", name="Temperatur Abschnitt 1", exact=True)).to_have_value("17.5")
    page.screenshot(path="/tmp/cul-max-room-light-desktop.png", full_page=True)
    card.get_by_role("button", name="Speichern", exact=True).click()
    expect(card.get_by_role("spinbutton", name="Komforttemperatur", exact=True)).to_be_disabled()
    expect(card.get_by_role("spinbutton", name="Temperatur Abschnitt 1", exact=True)).to_be_disabled()
    expect(card.get_by_text("Wartet auf Funkbudget", exact=False).first).to_be_visible()
    assert page.evaluate("calls.filter(c=>c.service==='save_room_config').length") == 1
    page.evaluate("finishFixture()")
    expect(card.get_by_role("spinbutton", name="Komforttemperatur", exact=True)).to_be_enabled()
    page.evaluate("resetFixture()")
    card.get_by_role("spinbutton", name="Ecotemperatur", exact=True).fill("18")
    page.once("dialog", lambda dialog: dialog.dismiss())
    card.locator("[data-room]").select_option("bed")
    expect(card.locator("[data-room]")).to_have_value("living")
    page.once("dialog", lambda dialog: dialog.accept())
    card.locator("[data-room]").select_option("bed")
    expect(card.locator("[data-room]")).to_have_value("bed")
    page.evaluate("resetFixture(); rooms[0].locks.temperature=true;pushFixture()")
    expect(card.get_by_role("spinbutton", name="Komforttemperatur", exact=True)).to_be_disabled()
    expect(card.get_by_role("spinbutton", name="Temperatur Abschnitt 1", exact=True)).to_be_enabled()
    page.evaluate("resetFixture();failNext=true")
    card.get_by_role("spinbutton", name="Komforttemperatur", exact=True).fill("22")
    card.get_by_role("button", name="Speichern", exact=True).click()
    expect(card.get_by_text("Konfiguration wurde zwischenzeitlich geändert. Bitte neu laden.", exact=True)).to_be_visible()
    expect(card.get_by_role("spinbutton", name="Komforttemperatur", exact=True)).to_have_value("22")
    page.evaluate("resetFixture();rooms[0].values.week_profile.monday=null;rooms[0].mixed=['monday'];card._day='monday';pushFixture()")
    expect(card.get_by_text("Kein gemeinsames Tagesprofil.", exact=False)).to_be_visible()
    card.get_by_role("button", name="Neuen Tagesplan anlegen").click()
    expect(card.get_by_role("button", name="Tag auf andere Tage kopieren …")).to_be_disabled()
    card.get_by_role("spinbutton", name="Temperatur Abschnitt 1", exact=True).fill("20")
    expect(card.get_by_role("button", name="Tag auf andere Tage kopieren …")).to_be_enabled()
    page.evaluate("resetFixture();document.body.classList.add('dark')")
    page.set_viewport_size({"width": 360, "height": 1000})
    expect(card.get_by_role("button", name="Speichern", exact=True)).to_be_visible()
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    card.get_by_role("button", name="Hilfe zu Fenster-offen-Dauer", exact=True).click()
    expect(card.locator("#help-window_open_duration")).to_be_visible()
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    page.screenshot(path="/tmp/cul-max-room-tooltip-mobile.png", full_page=True)
    card.get_by_role("button", name="Hilfe zu Fenster-offen-Dauer", exact=True).click()
    expect(card.locator("#help-window_open_duration")).to_be_hidden()
    card.get_by_role("button", name="Tag auf andere Tage kopieren …").click()
    card.get_by_role("button", name="Alle auswählen", exact=True).click()
    expect(card.get_by_role("button", name="Auf 6 Tage übernehmen")).to_be_visible()
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    page.screenshot(path="/tmp/cul-max-room-dark-mobile.png", full_page=True)
    card.get_by_role("button", name="Abbrechen", exact=True).click()
    assert page.evaluate("Object.keys(card._changes).length") == 0
    # Invalid five-minute boundaries still block saving with native time fields.
    card.get_by_label("Schaltzeit 2", exact=True).fill("06:01")
    expect(card.get_by_role("button", name="Speichern", exact=True)).to_be_disabled()
    card.get_by_label("Schaltzeit 2", exact=True).fill("06:05")
    expect(card.get_by_role("button", name="Speichern", exact=True)).to_be_enabled()
    page.evaluate("listeners.get('disconnected')()")
    expect(card.get_by_role("button", name="Speichern", exact=True)).to_be_disabled()
    page.evaluate("listeners.get('ready')()")
    expect(card.get_by_role("spinbutton", name="Komforttemperatur", exact=True)).to_be_enabled()
    assert not errors, errors
    print("Room card browser checks passed: editing, copy, save, locks, conflicts, rooms, reconnect, desktop/mobile and themes")
    browser.close()
